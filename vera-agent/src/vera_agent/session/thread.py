"""ThreadSession entity and context handover abstractions.

Manages message lifecycles, execution metrics, and persistence for agent sessions,
and provides standardized Handover Summary generation across sessions and subagents.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
import json
from pathlib import Path
import time
from typing import Any
import uuid


@dataclass
class ThreadSession:
    """Lightweight session entity.

    Centrally manages all state within an individual conversation thread:
    - Identifiers (thread_id, parent_thread_id, group_id)
    - Role identity (role: main, researcher, reviewer, etc.)
    - Message trajectory history (messages)
    - Resource consumption metrics (cost, n_calls)
    - Context handover export and snapshot persistence capabilities
    """

    thread_id: str = field(default_factory=lambda: f"th_{uuid.uuid4().hex[:12]}")
    role: str = "main"
    title: str = ""
    is_pinned: bool = False
    is_archived: bool = False
    parent_thread_id: str | None = None
    group_id: str | None = None
    created_at: float = field(default_factory=time.time)
    updated_at: float = field(default_factory=time.time)
    messages: list[dict] = field(default_factory=list)
    cost: float = 0.0
    n_calls: int = 0
    metadata: dict[str, Any] = field(default_factory=dict)

    def add_messages(self, *messages: dict) -> list[dict]:
        """Append messages to the session and update the last modified timestamp."""
        new_msgs = list(messages)
        self.messages.extend(new_msgs)
        self.updated_at = time.time()
        return new_msgs

    def add_cost(self, amount: float) -> None:
        """Accumulate model invocation cost for the current session."""
        self.cost += max(0.0, amount)

    def increment_calls(self) -> None:
        """Increment model call count."""
        self.n_calls += 1

    def get_touched_files(self) -> list[dict[str, str]]:
        """Scan historical message actions to extract touched (read/modified) files.

        Returns a list of dictionaries: [{"path": "foo/bar.py", "action": "read"|"write"|"edit"}, ...]
        """
        seen_paths: set[str] = set()
        touched: list[dict[str, str]] = []
        """Integrated operation file records."""
        for msg in self.messages:
            # Scan message['extra']['actions']
            actions = msg.get("extra", {}).get("actions", [])
            for act in actions:
                path = act.get("path")
                tool = act.get("tool_name") or ("bash" if "command" in act else "unknown")
                if path and path not in seen_paths:
                    seen_paths.add(path)
                    touched.append({"path": str(path), "action": tool})

        return touched

    def record_file_touch(self, path: str, action: str = "write") -> None:
        """Record an explicit file touch action in the session."""
        self.add_messages({
            "role": "system",
            "content": f"[FILE_TOUCH: {action} {path}]",
            "extra": {"actions": [{"path": str(path), "tool_name": action}]},
        })

    def get_last_assistant_text(self) -> str:
        """Extract the most recent text conclusion or response generated by the assistant."""
        for msg in reversed(self.messages):
            if msg.get("role") == "assistant":
                content = msg.get("content")
                if content and isinstance(content, str):
                    return content.strip()
                elif isinstance(content, list):
                    # Handle multimodal or content blocks
                    texts = [item.get("text", "") for item in content if isinstance(item, dict) and "text" in item]
                    if texts:
                        return "\n".join(texts).strip()
        # Fallback to exit submission if no assistant message text was found
        for msg in reversed(self.messages):
            if msg.get("role") == "exit":
                sub = msg.get("extra", {}).get("submission")
                if sub and str(sub) not in ("LimitsExceeded", "TimeExceeded", "RepeatedFormatError"):
                    return str(sub).strip()
        return ""

    def export_handover_summary(
        self,
        target_role: str = "main",
        extra_notes: str = "",
    ) -> str:
        """Generate a structured Markdown context handover summary.

        Core objectives:
        1. Prevent context window bloat and eliminate memory contamination / hallucinations;
        2. Provide a standardized protocol for Subagent reporting and cross-agent handover.
        """
        touched_files = self.get_touched_files()
        last_text = self.get_last_assistant_text()
        created_time_str = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(self.created_at))

        lines = [
            "# Context Handover Summary",
            "",
            "## 1. Source Metadata",
            f"- **Session ID**: `{self.thread_id}`",
            f"- **Source Role**: `{self.role}`",
            f"- **Target Role**: `{target_role}`",
            f"- **Created At**: {created_time_str}",
            f"- **Usage Metrics**: API Calls: {self.n_calls} | Cumulative Cost: ${self.cost:.4f}",
        ]

        if self.parent_thread_id:
            lines.append(f"- **Parent Session**: `{self.parent_thread_id}`")
        if self.group_id:
            lines.append(f"- **Workgroup**: `{self.group_id}`")

        lines.extend([
            "",
            "## 2. Touched Files",
        ])

        if touched_files:
            for item in touched_files:
                lines.append(f"- `[{item['action']}]` {item['path']}")
        else:
            lines.append("- *(No files directly touched or modified during this session)*")

        lines.extend([
            "",
            "## 3. Key Findings & Output",
        ])

        if last_text:
            lines.append(last_text)
        else:
            lines.append("- *(No explicit final output)*")

        if extra_notes:
            lines.extend([
                "",
                "## 4. Handover Notes & Next Steps",
                extra_notes.strip(),
            ])

        return "\n".join(lines) + "\n"

    def get_chat_history(
        self,
        prune_stale_observations: bool = True,
        keep_last_n_observations: int = 4,
        max_observation_chars: int = 500,
    ) -> list[dict]:
        """Return prepared chat history for model invocation with Level 1 observation pruning.

        Preserves complete causal structure and tool_call_id pairs while replacing
        bulky stale execution outputs (> max_observation_chars) from older turns with
        compact summaries to drastically cut prompt token consumption.
        """
        if not prune_stale_observations or not self.messages:
            return list(self.messages)

        # 1. Identify indices of all observation messages
        obs_indices = []
        for idx, msg in enumerate(self.messages):
            role = msg.get("role")
            msg_content = msg.get("content")
            content_str = str(msg_content or "")
            if role == "tool" or (role == "user" and ("<output>" in content_str or msg.get("name"))):
                obs_indices.append(idx)

        # Observation messages that should be kept intact
        preserve_indices = set(obs_indices[-keep_last_n_observations:]) if obs_indices else set()

        pruned_history = []
        for idx, msg in enumerate(self.messages):
            if idx in obs_indices and idx not in preserve_indices:
                content = str(msg.get("content") or "")
                if len(content) > max_observation_chars:
                    pruned_msg = dict(msg)
                    tool_name = msg.get("name") or "tool"
                    lines = content.count("\n")
                    pruned_content = (
                        f"[Output pruned: {tool_name} ({len(content)} chars, {lines} lines omitted. "
                        "Result already incorporated into earlier turn)]"
                    )
                    # If XML wrapped (<output>...</output>), retain tags
                    if "<output>" in content and "</output>" in content:
                        import re
                        pruned_msg["content"] = re.sub(
                            r"<output>.*?</output>",
                            f"<output>\n{pruned_content}\n</output>",
                            content,
                            flags=re.DOTALL,
                        )
                    else:
                        pruned_msg["content"] = pruned_content
                    pruned_history.append(pruned_msg)
                    continue
            pruned_history.append(msg)
        return pruned_history

    def compact(
        self,
        summary: str | None = None,
        keep_last_n_turns: int = 4,
    ) -> bool:
        """Execute Level 2 Boundary Compaction.

        Folds older conversational turns into a structured 4-slot context anchor block:
        1. Goals & Milestones
        2. Architectural Decisions & Invariants
        3. Touched Files
        4. Current WIP & Next Actions

        Preserves initial system and instance templates, along with recent hot turns.
        Returns True if compaction was performed, False if session is too short.
        """
        min_turns_needed = 2 + 2 + keep_last_n_turns
        if len(self.messages) < min_turns_needed:
            return False

        # Determine cutoff boundary for hot turns
        cut_idx = len(self.messages) - keep_last_n_turns
        # Ensure cut_idx does not land on an orphaned 'tool' observation
        while cut_idx < len(self.messages) and self.messages[cut_idx].get("role") == "tool":
            cut_idx += 1

        if cut_idx <= 2:
            return False

        if not summary:
            touched = self.get_touched_files()
            touched_str = "\n".join([f"- `[{t['action']}]` {t['path']}" for t in touched]) if touched else "- None"
            last_text = self.get_last_assistant_text() or "- In progress"
            task_desc = self.messages[1].get("content", "")[:400] if len(self.messages) > 1 else "Task in progress"
            summary = (
                "<context_compaction>\n"
                "## 1. 原始目标与当前里程碑 (Goals & Milestones)\n"
                f"{task_desc.strip()}\n\n"
                "## 2. 关键架构决策与不可变契约 (Architectural Decisions & Invariants)\n"
                "- 严格践行 7 大核心工程准则 (BLUF、范围授权、沙箱隔离)\n\n"
                "## 3. 已触碰与修改的核心文件 (Touched Files)\n"
                f"{touched_str}\n\n"
                "## 4. 当前进行中状态与遗留阻碍 (Current WIP & Next Actions)\n"
                f"{last_text}\n"
                "</context_compaction>"
            )

        compacted_msg = {
            "role": "user",
            "content": f"[SYSTEM COMPACTION ANCHOR: Earlier dialogue turns folded to conserve context window]\n\n{summary}",
            "extra": {"compaction": True, "timestamp": time.time()},
        }

        system_and_first = self.messages[:2]
        hot_turns = self.messages[cut_idx:]
        self.messages = system_and_first + [compacted_msg] + hot_turns
        self.updated_at = time.time()
        return True

    def create_derived_session(
        self,
        new_role: str = "main",
        extra_notes: str = "",
    ) -> ThreadSession:
        """Execute Level 3 Epoch Compaction / Session Rebirth.

        Derives a clean new ThreadSession linked to parent_thread_id,
        inheriting the structured Handover Summary and metadata.
        """
        handover_text = self.export_handover_summary(target_role=new_role, extra_notes=extra_notes)
        new_session = ThreadSession(
            role=new_role,
            parent_thread_id=self.thread_id,
            group_id=self.group_id,
            metadata={"parent_cost": self.cost, "parent_calls": self.n_calls},
        )
        new_session.add_messages({
            "role": "user",
            "content": f"[INHERITED CONTEXT FROM SESSION {self.thread_id}]\n\n{handover_text}",
            "extra": {"inherited": True, "parent_thread_id": self.thread_id},
        })
        return new_session

    def to_dict(self) -> dict[str, Any]:
        """Serialize the current session into a dictionary."""
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ThreadSession:
        """Deserialize a ThreadSession entity from a dictionary."""
        filtered = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        return cls(**filtered)

    def save(self, file_path: Path | str) -> Path:
        """Persist the session state to a JSON file."""
        path = Path(file_path).resolve()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")
        return path

    @classmethod
    def load(cls, file_path: Path | str) -> ThreadSession:
        """Restore a ThreadSession entity from a disk JSON snapshot."""
        path = Path(file_path).resolve()
        data = json.loads(path.read_text(encoding="utf-8"))
        return cls.from_dict(data)
